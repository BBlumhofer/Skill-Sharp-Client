"""Generate src/OpenSmi.Client/Unit.g.cs from the installed opensmi-core unit_all.py.

Usage: python tools/generate_units.py
"""

import json
from importlib.metadata import version
from pathlib import Path

from opensmi.core import unit_all
from opensmi.core.unit_all import Unit

OUT = Path(__file__).resolve().parent.parent / "src" / "OpenSmi.Client" / "Unit.g.cs"


def pascal(name: str) -> str:
    """CENTIMETRE -> Centimetre, ACTUAL_360 -> Actual360."""
    return "".join(part.capitalize() for part in name.split("_"))


def main() -> None:
    # Iterating the enum skips Python aliases, so every C# value is unique.
    units = list(Unit)
    names = [pascal(u.name) for u in units]
    assert len(set(names)) == len(names), "PascalCase names collide"
    assert all(n[0].isalpha() for n in names), "PascalCase name starts with a digit"
    lines = [
        "// <auto-generated>",
        "// Generated by tools/generate_units.py, do not edit.",
        f"// Source: {Path(unit_all.__file__).name} from opensmi-core {version('opensmi-core')}",
        "// </auto-generated>",
        "#nullable enable",
        "namespace OpenSmi.Client;",
        "",
        "/// <summary>UN/CEFACT Rec 20 units; the value is the OPC UA unit id. Names are opensmi-core's in PascalCase.</summary>",
        "public enum Unit",
        "{",
        *(f"    {pascal(u.name)} = {u.ua_unit_id}," for u in units),
        "}",
        "",
        "public static partial class Units",
        "{",
        "    // Symbol and opensmi-core name (the EUInformation description).",
        "    private static readonly Dictionary<Unit, (string Symbol, string Name)> Info = new()",
        "    {",
        # json string literals are valid C# string literals
        *(f"        [Unit.{pascal(u.name)}] = ({json.dumps(u.symbol, ensure_ascii=False)}, \"{u.name}\")," for u in units),
        "    };",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(units)} units to {OUT}")


if __name__ == "__main__":
    main()
